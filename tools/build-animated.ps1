# Embeds Narsil's animated loops for the hooks module: each
# assets/anim/[etapa<N>/]<pose>-<claro|oscuro>.webp (an animated WebP with
# transparency) goes into hooks/art/animated.ts, which hooks/sprite.ts prefers
# over the still picture of that pose.
#   powershell -ExecutionPolicy Bypass -File tools/build-animated.ps1
$root = Split-Path -Parent $PSScriptRoot
$dir = Join-Path $root 'assets\anim'

# Size of the canvas, from the WebP's VP8X header (24-bit, minus one).
function Get-WebpSize([byte[]]$b) {
  if ([Text.Encoding]::ASCII.GetString($b, 12, 4) -ne 'VP8X') { throw 'not an extended (animated) WebP' }
  $w = 1 + $b[24] + ($b[25] -shl 8) + ($b[26] -shl 16)
  $h = 1 + $b[27] + ($b[28] -shl 8) + ($b[29] -shl 16)
  return @($w, $h)
}

$byStage = @{}
if (Test-Path $dir) {
  foreach ($f in Get-ChildItem $dir -Recurse -Filter *.webp) {
    if ($f.BaseName -notmatch '^(.+)-(claro|oscuro)$') { continue }
    $pose = $matches[1]; $theme = $matches[2]
    $stage = if ($f.Directory.Name -match '^etapa(\d)$') { [int]$matches[1] } else { 1 }
    $bytes = [IO.File]::ReadAllBytes($f.FullName)
    $size = Get-WebpSize $bytes
    $entry = "      ${pose}: { src: 'data:image/webp;base64,$([Convert]::ToBase64String($bytes))', width: $($size[0]), height: $($size[1]) },"
    if (-not $byStage[$stage]) { $byStage[$stage] = @{} }
    if (-not $byStage[$stage][$theme]) { $byStage[$stage][$theme] = @() }
    $byStage[$stage][$theme] += $entry
  }
}

$lines = @(
  '// Generated by tools/build-animated.ps1 from assets/anim: do not edit by hand.',
  "import type { Art } from '../art'",
  '// Animated loops, by stage of her growth, then by theme and pose.',
  'export const ANIMATED: Record<number, { claro?: Record<string, Art>; oscuro?: Record<string, Art> }> = {'
)
foreach ($stage in ($byStage.Keys | Sort-Object)) {
  $lines += "  ${stage}: {"
  foreach ($theme in ($byStage[$stage].Keys | Sort-Object)) {
    $lines += "    ${theme}: {"
    $lines += $byStage[$stage][$theme]
    $lines += '    },'
  }
  $lines += '  },'
}
$lines += '}'
$out = Join-Path $root 'hooks\art\animated.ts'
[IO.File]::WriteAllText($out, ($lines -join "`n") + "`n", (New-Object Text.UTF8Encoding $false))
Write-Output "Wrote $out"
