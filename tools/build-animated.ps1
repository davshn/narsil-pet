# Embeds Narsil's animated loops for the hooks module: each
# assets/anim/[etapa<N>/]<pose>-<claro|oscuro>.webp (an animated WebP with
# transparency, made by tools/encode-anim.ps1) goes into
# hooks/art/anim/etapa<N>-<theme>.ts, one file per stage and theme (the engine
# reads no file over 1 MiB), gathered by hooks/art/animated.ts, which
# hooks/sprite.ts prefers over the still picture of that pose.
#   powershell -ExecutionPolicy Bypass -File tools/build-animated.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$dir = Join-Path $root 'assets\anim'
$outDir = Join-Path $root 'hooks\art\anim'
$utf8 = New-Object Text.UTF8Encoding $false
# Both themes' loops share the band's 131072 characters with the rest of her drawing.
$MAX_BYTES = 40 * 1024

# Size of the canvas, from the WebP's VP8X header (24-bit, minus one).
function Get-WebpSize([byte[]]$b) {
  if ([Text.Encoding]::ASCII.GetString($b, 12, 4) -ne 'VP8X') { throw 'not an extended (animated) WebP' }
  $w = 1 + $b[24] + ($b[25] -shl 8) + ($b[26] -shl 16)
  $h = 1 + $b[27] + ($b[28] -shl 8) + ($b[29] -shl 16)
  return @($w, $h)
}

$groups = @{}
if (Test-Path $dir) {
  foreach ($f in Get-ChildItem $dir -Recurse -Filter *.webp | Sort-Object FullName) {
    if ($f.BaseName -notmatch '^(.+)-(claro|oscuro)$') { continue }
    $pose = $matches[1]; $theme = $matches[2]
    $stage = if ($f.Directory.Name -match '^etapa(\d)$') { [int]$matches[1] } else { 1 }
    $bytes = [IO.File]::ReadAllBytes($f.FullName)
    if ($bytes.Length -gt $MAX_BYTES) { throw "$($f.FullName) is $($bytes.Length) bytes, over ${MAX_BYTES}: re-encode it smaller" }
    $size = Get-WebpSize $bytes
    $key = "etapa$stage-$theme"
    if (-not $groups[$key]) { $groups[$key] = @{ stage = $stage; theme = $theme; entries = @() } }
    $groups[$key].entries += "  ${pose}: { src: 'data:image/webp;base64,$([Convert]::ToBase64String($bytes))', width: $($size[0]), height: $($size[1]) },"
  }
}

if (Test-Path $outDir) { Remove-Item (Join-Path $outDir '*.ts') }
New-Item -ItemType Directory -Force $outDir | Out-Null
$imports = @(); $byStage = @{}
foreach ($key in ($groups.Keys | Sort-Object)) {
  $gr = $groups[$key]
  $lines = @('// Generated by tools/build-animated.ps1 from assets/anim: do not edit by hand.', "import type { Art } from '../../art'", 'export const LOOPS: Record<string, Art> = {') + $gr.entries + '}'
  [IO.File]::WriteAllText((Join-Path $outDir "$key.ts"), ($lines -join "`n") + "`n", $utf8)
  $name = 'etapa' + $gr.stage + ($gr.theme.Substring(0, 1).ToUpper() + $gr.theme.Substring(1))
  $imports += "import { LOOPS as $name } from './anim/$key'"
  if (-not $byStage[$gr.stage]) { $byStage[$gr.stage] = @() }
  $byStage[$gr.stage] += "$($gr.theme): $name"
}

$lines = @('// Generated by tools/build-animated.ps1 from assets/anim: do not edit by hand.', "import type { Art } from '../art'") + $imports +
  '// Animated loops, by stage of her growth, then by theme and pose.' +
  'export const ANIMATED: Record<number, { claro?: Record<string, Art>; oscuro?: Record<string, Art> }> = {'
foreach ($stage in ($byStage.Keys | Sort-Object)) { $lines += "  ${stage}: { $($byStage[$stage] -join ', ') }," }
$lines += '}'
[IO.File]::WriteAllText((Join-Path $root 'hooks\art\animated.ts'), ($lines -join "`n") + "`n", $utf8)
Write-Output "Wrote hooks/art/animated.ts and $($groups.Count) loop file(s)"
